"""Converts the browser game's car models (exported from the running game as triangles grouped by material)
into compact Luau modules the Roblox client turns into meshes with EditableMesh.
Vertices are welded where faces meet smoothly and split at creases (> 38°), positions are quantised to
1/2000 stud, normals to 1/127, and everything is packed into base64 strings."""
import json, sys, base64, struct, math
import numpy as np

SRC = sys.argv[1]; OUT = sys.argv[2]
S = 3.5  # studs per metre
CREASE = math.cos(math.radians(38))
cars = json.load(open(SRC))

def lua_str(d):
    # long base64 strings as 1000-character lines: Studio's script tools choke on 100k-character lines
    if len(d) <= 2000: return '"' + d + '"'
    return 'table.concat({\n\t\t\t\t' + ',\n\t\t\t\t'.join('"' + d[i:i + 1000] + '"' for i in range(0, len(d), 1000)) + ',\n\t\t\t})'

def to_roblox(p):  # browser (+z forward, +x left) -> Roblox car space (-z forward), studs
    p = np.asarray(p, dtype=np.float64).reshape(-1, 3)
    return np.stack([-p[:, 0] * S, p[:, 1] * S, -p[:, 2] * S], 1)

def weld(tris):
    """tris: (n*3, 3) corner positions. Returns verts, normals, indices."""
    n = len(tris) // 3
    P = tris.reshape(n, 3, 3)
    fn = np.cross(P[:, 1] - P[:, 0], P[:, 2] - P[:, 0])
    area = np.linalg.norm(fn, axis=1); keep = area > 1e-9
    P, fn, area = P[keep], fn[keep], area[keep]
    fnu = fn / area[:, None]
    n = len(P)
    buckets = {}
    corner_vert = np.zeros((n, 3), dtype=np.int64)
    verts, nsum = [], []
    for t in range(n):
        for k in range(3):
            key = tuple(np.round(P[t, k] / 0.001).astype(np.int64))
            cl = buckets.setdefault(key, [])
            hit = -1
            for vi in cl:
                v = nsum[vi]; l = np.linalg.norm(v)
                if l > 0 and np.dot(v / l, fnu[t]) > CREASE: hit = vi; break
            if hit < 0:
                hit = len(verts); verts.append(P[t, k]); nsum.append(np.zeros(3)); cl.append(hit)
            nsum[hit] = nsum[hit] + fn[t]  # area-weighted
            corner_vert[t, k] = hit
    V = np.array(verts); N = np.array(nsum); N /= np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-12)
    return V, N, corner_vert

def pack(V, N, I):
    c = (V.min(0) + V.max(0)) / 2
    q = np.round((V - c) * 2000).astype(np.int64)
    assert np.abs(q).max() < 32767, 'mesh too big for int16'
    nq = np.clip(np.round(N * 127), -127, 127).astype(np.int8)
    b = bytearray()
    b += struct.pack('<HH', len(V), len(I))
    b += q.astype('<i2').tobytes()
    b += nq.tobytes()
    b += I.astype('<u2').tobytes()
    return base64.b64encode(bytes(b)).decode(), c

def kind(key, g):
    if 'T' in key.split('#')[-1] and g['op'] < 0.99: return 'glass' if g['op'] > 0.05 else 'hidden'
    if g.get('em'): return 'lamp'
    if g['metal'] > 0.6: return 'metal'
    return 'plastic'

total = 0
for cid, car in cars.items():
    groups = car['groups']
    # the paint is the group whose colour matches the car colour and has the most triangles
    paintKey = next((k for k, g in groups.items() if g.get('paint') and g['op'] >= 0.99 and not k.startswith('wheel:')), None)
    wheelsB = np.array(car['wheels'])
    wheelsR = to_roblox(wheelsB)
    body_out, wheel_out = [], [[] for _ in range(len(wheelsR))]
    for key, g in groups.items():
        if g['op'] < 0.05: continue
        tri = to_roblox(g['p'])
        k = 'paint' if key == paintKey else kind(key, g)
        if key.startswith('wheel:'):
            n = len(tri) // 3
            cent = tri.reshape(n, 3, 3).mean(1)
            owner = np.argmin(((cent[:, None, :] - wheelsR[None, :, :]) ** 2).sum(2), 1)
            for w in range(len(wheelsR)):
                sel = tri.reshape(n, 3, 3)[owner == w].reshape(-1, 3) - wheelsR[w]
                if len(sel) == 0: continue
                V, N, I = weld(sel)
                data, c = pack(V, N, I.reshape(-1))
                spin = g['col'] not in ('6a6d73', 'c81e1e')  # disc and caliper turn with steering only
                wheel_out[w].append((k, g['col'], data, c, len(V), len(I), spin))
        else:
            V, N, I = weld(tri)
            data, c = pack(V, N, I.reshape(-1))
            body_out.append((k, g['col'], data, c, len(V), len(I), g.get('em'), g['op']))
            total += len(V)
    lines = [f'-- {cid}: generated by tools/make_car_meshes.py from the browser game. Do not edit.', 'return {', '\tbody = {']
    for k, col, data, c, nv, nt, em, op in body_out:
        lines.append(f'\t\t{{ kind = "{k}", color = "{col}", glow = {("\"" + em + "\"") if em else "nil"}, opacity = {op:.2f}, center = {{ {c[0]:.3f}, {c[1]:.3f}, {c[2]:.3f} }}, data = {lua_str(data)} }},')
    lines.append('\t},')
    lines.append('\twheels = {')
    for w, parts in enumerate(wheel_out):
        p = wheelsR[w]
        front = wheelsB[w][2] > 0
        lines.append(f'\t\t{{ pos = {{ {p[0]:.3f}, {p[1]:.3f}, {p[2]:.3f} }}, front = {str(bool(front)).lower()}, parts = {{')
        for k, col, data, c, nv, nt, spin in parts:
            lines.append(f'\t\t\t{{ kind = "{k}", color = "{col}", spin = {str(spin).lower()}, center = {{ {c[0]:.3f}, {c[1]:.3f}, {c[2]:.3f} }}, data = {lua_str(data)} }},')
        lines.append('\t\t} },')
    lines.append('\t},')
    lines.append('}')
    open(f'{OUT}/{cid}.luau', 'w').write('\n'.join(lines) + '\n')
    print(cid, 'body parts', len(body_out), 'wheel parts', sum(len(w) for w in wheel_out), 'body verts', sum(b[4] for b in body_out), 'size KB', round(len('\n'.join(lines)) / 1024))
